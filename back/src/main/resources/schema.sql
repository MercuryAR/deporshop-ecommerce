-- ============================================================
-- DeporShop: esquema de órdenes y pagos para H2
-- Spring Boot ejecuta este archivo después de crear las tablas
-- administradas por JPA (categorias y productos).
-- ============================================================

CREATE TABLE IF NOT EXISTS ordenes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(40) NOT NULL UNIQUE,

    cliente_nombre VARCHAR(120) NOT NULL,
    cliente_email VARCHAR(180) NOT NULL,
    cliente_telefono VARCHAR(40) NOT NULL,

    direccion VARCHAR(220) NOT NULL,
    ciudad VARCHAR(120) NOT NULL,
    codigo_postal VARCHAR(20) NOT NULL,

    total DECIMAL(14, 2) NOT NULL CHECK (total >= 0),
    moneda CHAR(3) NOT NULL DEFAULT 'ARS',
    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE_PAGO',

    creada_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizada_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_orden_estado CHECK (
        estado IN (
            'PENDIENTE_PAGO',
            'PAGADA',
            'PREPARANDO',
            'ENVIADA',
            'ENTREGADA',
            'CANCELADA'
        )
    )
);

CREATE TABLE IF NOT EXISTS orden_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id BIGINT NOT NULL,
    producto_id BIGINT,

    -- Copia histórica para conservar el detalle aunque cambie el producto.
    producto_nombre VARCHAR(180) NOT NULL,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario DECIMAL(14, 2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal DECIMAL(14, 2) NOT NULL CHECK (subtotal >= 0),

    CONSTRAINT fk_orden_items_orden
        FOREIGN KEY (orden_id) REFERENCES ordenes(id) ON DELETE CASCADE,
    CONSTRAINT fk_orden_items_producto
        FOREIGN KEY (producto_id) REFERENCES productos(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS pagos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id BIGINT NOT NULL,

    proveedor VARCHAR(40) NOT NULL,
    metodo VARCHAR(50) NOT NULL,
    referencia_proveedor VARCHAR(160),

    importe DECIMAL(14, 2) NOT NULL CHECK (importe >= 0),
    moneda CHAR(3) NOT NULL DEFAULT 'ARS',
    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE',

    -- Solo información técnica no sensible devuelta por la pasarela.
    metadata VARCHAR(2000),
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_pagos_orden
        FOREIGN KEY (orden_id) REFERENCES ordenes(id) ON DELETE CASCADE,
    CONSTRAINT uq_pago_referencia UNIQUE (referencia_proveedor),
    CONSTRAINT ck_pago_estado CHECK (
        estado IN (
            'PENDIENTE',
            'APROBADO',
            'RECHAZADO',
            'CANCELADO',
            'REEMBOLSADO'
        )
    )
);

-- Cuando Hibernate crea las tablas primero, conserva igualmente la relación
-- histórica opcional entre el ítem y el producto.
ALTER TABLE orden_items ADD CONSTRAINT IF NOT EXISTS fk_orden_items_producto
    FOREIGN KEY (producto_id) REFERENCES productos(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_ordenes_email
    ON ordenes(cliente_email);

CREATE INDEX IF NOT EXISTS idx_ordenes_estado
    ON ordenes(estado);

CREATE INDEX IF NOT EXISTS idx_ordenes_fecha
    ON ordenes(creada_en);

CREATE INDEX IF NOT EXISTS idx_orden_items_orden
    ON orden_items(orden_id);

CREATE INDEX IF NOT EXISTS idx_pagos_orden
    ON pagos(orden_id);

CREATE INDEX IF NOT EXISTS idx_pagos_estado
    ON pagos(estado);
